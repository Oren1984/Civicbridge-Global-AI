"""Outbound e-mail to the local mail sink (Mailpit). Nothing leaves the machine in the default setup."""
from __future__ import annotations

import smtplib
from email.message import EmailMessage

from app.config import get_settings


def send(to: str, subject: str, body: str) -> None:
    s = get_settings()
    msg = EmailMessage()
    msg["From"] = s.mail_from
    msg["To"] = to
    msg["Subject"] = f"[CivicBridge local] {subject}"
    msg.set_content(
        body
        + "\n\n--\nThis message was generated by a local CivicBridge demo installation using synthetic data."
    )
    with smtplib.SMTP(s.smtp_host, s.smtp_port, timeout=10) as smtp:
        smtp.send_message(msg)
